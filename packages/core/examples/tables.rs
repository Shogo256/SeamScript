//! cargo run --release --example tables -- js/tables.ts
//!
//! Writes the per-code-point properties of `src/props.rs` as a TypeScript module
//! for the JavaScript side (`js/core.ts`). Run by `scripts/build.mjs`.

use seamscript_core::{UNICODE_VERSION, props};

fn base36(mut n: u32) -> String {
    const DIGITS: &[u8] = b"0123456789abcdefghijklmnopqrstuvwxyz";
    let mut out = Vec::new();
    loop {
        out.push(DIGITS[(n % 36) as usize]);
        n /= 36;
        if n == 0 {
            break;
        }
    }
    out.reverse();
    String::from_utf8(out).unwrap()
}

fn main() {
    let path = std::env::args().nth(1).expect("usage: tables <output.ts>");
    let runs: Vec<String> = props::runs().iter().map(|&(n, p)| format!("{p}{}", base36(n))).collect();
    let (major, minor, update) = UNICODE_VERSION;
    let ts = format!(
        "// Generated by examples/tables.rs from the Rust crate; do not edit.\n\
         // Properties of every code point from U+0000 to U+10FFFF (src/props.rs), as\n\
         // comma-separated runs: the properties as one digit ({nfc} NFC-safe | {nfd} NFD-safe |\n\
         // {solo} solo), then the run's length in base 36.\n\
         export const TABLES_UNICODE_VERSION = \"{major}.{minor}.{update}\";\n\
         export const PROPS = \"{}\";\n",
        runs.join(","),
        nfc = props::NFC_SAFE,
        nfd = props::NFD_SAFE,
        solo = props::SOLO,
    );
    std::fs::write(&path, ts).expect("cannot write the output");
}
