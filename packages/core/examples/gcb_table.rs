//! cargo run --example gcb_table
//!
//! Writes `src/gcb_table.rs`: the Grapheme_Cluster_Break, Extended_Pictographic
//! and Indic_Conjunct_Break properties of every code point, which is all that
//! the rules of UAX #29 for extended grapheme clusters look at. They come from
//! Unicode's own data files in `.ucd/` (`scripts/fetch-ucd.sh` downloads them,
//! checked by SHA-256). The tests in `src/segment.rs` compare the segmentation
//! built on this table with unicode-segmentation's, next to every code point.

use seamscript_core::segment::{EXT_PICT, INCB_CONSONANT, INCB_EXTEND, INCB_LINKER};
use std::fmt::Write;
use std::fs;

const VERSION: (u8, u8, u8) = (17, 0, 0);
const END: usize = 0x110000;
/// Must match `segment::BLOCK`.
const BLOCK: usize = 128;

/// The data lines of a UCD file, split at `;` and trimmed, comments removed.
fn rows(file: &str) -> Vec<Vec<String>> {
    let (a, b, c) = VERSION;
    let path = format!("{}/.ucd/{a}.{b}.{c}/{file}", env!("CARGO_MANIFEST_DIR"));
    let text = fs::read_to_string(&path).unwrap_or_else(|e| panic!("{path}: {e} (run scripts/fetch-ucd.sh)"));
    text.lines()
        .map(|line| line.split('#').next().unwrap().trim())
        .filter(|line| !line.is_empty())
        .map(|line| line.split(';').map(|f| f.trim().to_string()).collect())
        .collect()
}

fn range(field: &str) -> std::ops::RangeInclusive<usize> {
    let (a, b) = field.split_once("..").unwrap_or((field, field));
    usize::from_str_radix(a, 16).unwrap()..=usize::from_str_radix(b, 16).unwrap()
}

fn main() {
    let mut props = vec![0u8; END];
    for row in rows("GraphemeBreakProperty.txt") {
        let gcb = match row[1].as_str() {
            "CR" => 1,
            "LF" => 2,
            "Control" => 3,
            "Extend" => 4,
            "ZWJ" => 5,
            "Regional_Indicator" => 6,
            "Prepend" => 7,
            "SpacingMark" => 8,
            "L" => 9,
            "V" => 10,
            "T" => 11,
            "LV" => 12,
            "LVT" => 13,
            other => panic!("unknown Grapheme_Cluster_Break value {other}"),
        };
        range(&row[0]).for_each(|cp| props[cp] |= gcb);
    }
    for row in rows("emoji-data.txt") {
        if row[1] == "Extended_Pictographic" {
            range(&row[0]).for_each(|cp| props[cp] |= EXT_PICT);
        }
    }
    for row in rows("DerivedCoreProperties.txt") {
        if row.len() == 3 && row[1] == "InCB" {
            let incb = match row[2].as_str() {
                "Consonant" => INCB_CONSONANT,
                "Linker" => INCB_LINKER,
                "Extend" => INCB_EXTEND,
                other => panic!("unknown Indic_Conjunct_Break value {other}"),
            };
            range(&row[0]).for_each(|cp| props[cp] |= incb);
        }
    }

    // Two levels: blocks of 128 code points, each stored once however often it
    // repeats, and for every block of the code space the one it is.
    let mut blocks: Vec<&[u8]> = Vec::new();
    let mut index: Vec<u8> = Vec::new();
    for block in props.chunks(BLOCK) {
        let i = blocks.iter().position(|&b| b == block).unwrap_or_else(|| {
            blocks.push(block);
            blocks.len() - 1
        });
        index.push(u8::try_from(i).expect("more than 256 distinct blocks"));
    }

    let (a, b, c) = VERSION;
    let mut out = String::new();
    writeln!(out, "// Generated by `cargo run --example gcb_table` from Unicode {a}.{b}.{c}'s").unwrap();
    writeln!(out, "// GraphemeBreakProperty.txt, emoji-data.txt and DerivedCoreProperties.txt.").unwrap();
    writeln!(out, "// Do not edit; see src/segment.rs for the encoding.").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "pub const VERSION: (u8, u8, u8) = ({a}, {b}, {c});").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "/// For each block of {BLOCK} code points, which of `BLOCKS` holds its properties.").unwrap();
    writeln!(out, "#[rustfmt::skip]").unwrap();
    writeln!(out, "pub static INDEX: [u8; {}] = [", index.len()).unwrap();
    for chunk in index.chunks(32) {
        let line: Vec<String> = chunk.iter().map(|i| i.to_string()).collect();
        writeln!(out, "    {},", line.join(", ")).unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "/// The distinct blocks, {BLOCK} code points' properties each, one after another.").unwrap();
    writeln!(out, "#[rustfmt::skip]").unwrap();
    writeln!(out, "pub static BLOCKS: [u8; {}] = [", blocks.len() * BLOCK).unwrap();
    for block in &blocks {
        for chunk in block.chunks(32) {
            let line: Vec<String> = chunk.iter().map(|p| format!("0x{p:02x}")).collect();
            writeln!(out, "    {},", line.join(", ")).unwrap();
        }
    }
    writeln!(out, "];").unwrap();
    let path = format!("{}/src/gcb_table.rs", env!("CARGO_MANIFEST_DIR"));
    fs::write(&path, out).unwrap();
    eprintln!("{path}: {} distinct blocks", blocks.len());
}
